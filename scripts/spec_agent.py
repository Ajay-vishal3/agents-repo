"""Spec agent: reads requirements.md, calls GitHub Models, writes specification.md.

Runs inside GitHub Actions. Expects two checkouts in the workspace:
  story/   -> the stories repo, on the story branch
  agents/  -> this agents repo (for the prompt file)

Environment variables:
  GITHUB_TOKEN  token with `models: read` permission (the workflow's built-in token)
  STORY_ID      e.g. DEMO-1
  MODEL         e.g. openai/gpt-4o-mini
"""

import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

ENDPOINT = "https://models.github.ai/inference/chat/completions"
MAX_REQUIREMENT_CHARS = 16000  # free tier allows about 8,000 input tokens per request


def main() -> int:
    story_id = os.environ["STORY_ID"]
    model = os.environ.get("MODEL", "openai/gpt-4o-mini")
    token = os.environ["GITHUB_TOKEN"]

    requirements_path = Path(f"story/stories/{story_id}/requirements.md")
    output_path = Path(f"story/stories/{story_id}/specification.md")
    prompt_path = Path("agents/prompts/spec-agent.md")

    if not requirements_path.exists():
        print(f"ERROR: {requirements_path} not found on the story branch.", file=sys.stderr)
        return 1

    requirements = requirements_path.read_text(encoding="utf-8")
    if len(requirements) > MAX_REQUIREMENT_CHARS:
        print(
            f"ERROR: requirements.md is {len(requirements)} characters. "
            f"Keep it under {MAX_REQUIREMENT_CHARS} for the free GitHub Models tier.",
            file=sys.stderr,
        )
        return 1

    system_prompt = prompt_path.read_text(encoding="utf-8")

    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {
                "role": "user",
                "content": f"Story ID: {story_id}\n\nRequirement:\n\n{requirements}",
            },
        ],
    }

    request = urllib.request.Request(
        ENDPOINT,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            result = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as error:
        body = error.read().decode("utf-8", errors="replace")
        print(f"ERROR: GitHub Models returned HTTP {error.code}", file=sys.stderr)
        print(body, file=sys.stderr)
        hints = {
            400: "Bad request. Check the model id, or the input may be too large.",
            401: "Not authorized. Does the job have `permissions: models: read`?",
            403: "Forbidden. Models may not be enabled for this account, or the job lacks `models: read`.",
            404: "Model not found. List valid ids at https://models.github.ai/catalog/models",
            413: "Input too large for the free tier (about 8,000 tokens).",
            429: "Rate limit reached (requests per minute or per day). Wait and re-run.",
        }
        if error.code in hints:
            print("HINT:", hints[error.code], file=sys.stderr)
        return 1

    try:
        specification = result["choices"][0]["message"]["content"].strip()
    except (KeyError, IndexError, TypeError):
        print("ERROR: unexpected response shape:", json.dumps(result)[:2000], file=sys.stderr)
        return 1

    footer = (
        "\n\n---\n"
        f"*Draft generated by the spec agent using `{model}`. "
        "Review carefully before approving.*\n"
    )
    output_path.write_text(specification + footer, encoding="utf-8")
    print(f"Wrote {output_path} ({len(specification)} characters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
